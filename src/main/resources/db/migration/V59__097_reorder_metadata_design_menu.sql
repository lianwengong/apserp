/* 重排「平台管理 → 元数据设计（9003）」下的菜单顺序
   ------------------------------------------------------------------
   按"配置一个模块"的真实操作顺序排列：
     定义模块 → 配终端可见 → 挂菜单 → 定义数据对象 → 子表关系
     → 状态机 → 页面编排 → 打印模板 → 设计器总览 → 发布与回滚

   说明：菜单顺序由 plat.Menu.Sort 决定（ORDER BY Sort, Id），
   这里按 Code 统一改 Sort，覆盖所有租户中的同编码节点，保证各租户一致。
   ===================================================================== */
SET NOCOUNT ON;
GO
EXEC sys.sp_set_session_context N'BypassRls', 1;
GO
UPDATE m
SET Sort = v.Sort
FROM plat.Menu m
JOIN (VALUES
        ('900304', 10),   -- 模块管理
        ('900309', 20),   -- 终端与功能
        ('900305', 30),   -- 菜单管理
        ('900301', 40),   -- 数据对象与字段
        ('900302', 50),   -- 子表关系
        ('900303', 60),   -- 状态机
        ('900310', 70),   -- 页面编排
        ('900307', 80),   -- 打印模板
        ('900308', 90),   -- 设计器中心（总览入口）
        ('900306', 100)   -- 发布与回滚（最后一步）
     ) AS v(Code, Sort) ON v.Code = m.Code
WHERE m.IsDeleted = 0;
GO
